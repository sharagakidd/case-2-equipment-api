import * as z from 'zod';

// Поля учётной записи. Пароль ограничен 72 байтами: столько обрабатывает bcrypt,
// более длинный хвост молча отбрасывался бы.
const credentials = {
  email: z.email('Некорректный email'),
  password: z.string().min(8, 'Пароль должен быть не короче 8 символов').max(72, 'Пароль длиннее 72 символов'),
};

// Регистрация открыта всем, поэтому роль в теле не принимаем: новая учётная запись
// всегда viewer (значение по умолчанию подставляет сервис). Роли выдаёт админ.
export const registerSchema = z.object(credentials);

// Вход: только почта и пароль, ничего лишнего.
export const loginSchema = z.object(credentials);
